"""Generate docs/commands.md from the argparse definitions in spritewright/cli.py.

    python tools/gen_command_docs.py            write docs/commands.md
    python tools/gen_command_docs.py --check    exit 1 if docs/commands.md is out of date

The output is built from the parser's actions (not from argparse's own help formatter), so it is the
same on every Python version and terminal width. tests/test_release.py fails when the file is stale.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from spritewright import __version__  # noqa: E402
from spritewright.cli import build_parser  # noqa: E402

OUT = ROOT / "docs" / "commands.md"

GROUPS = [
    ("Game / character pipeline (`outputs/<Game>/`)",
     ["build", "context", "game-new", "game-style", "game-palette-add", "char-new", "char-export",
      "outputs-index"]),
    ("Review / quality", ["check", "contact", "inspect", "preview", "diff", "info", "validate", "ascii",
                          "clean", "blueprint"]),
    ("Output / export", ["render", "sheet", "gif", "unity-sheet", "export-json", "run"]),
    ("Palettes", ["palettes", "palette-show", "palette-create", "attach-palette", "ramp", "quantize"]),
    ("Editing (overwrite the source .json unless -o)", ["new", "outline", "shade", "frame"]),
    ("Animation", ["templates", "anim-apply", "tween", "oscillate"]),
    ("Import / cleanup", ["import", "depixelize", "grid-detect"]),
    ("Setup", ["install-skill"]),
]

HEADER = """# Command reference

<!-- Generated by tools/gen_command_docs.py from spritewright/cli.py - do not edit by hand. -->

All commands of `spritewright` {version}. Run them as `spritewright <command>` (installed) or
`python spritewright.py <command>` (source checkout); `spritewright <command> -h` prints the same
information.

General rules:

- `SRC` is a sprite source: a grid `.json`, a rig `.json` or a `.py` drawing script, given as a path or
  as a project-relative name (`examples/sprites/hero.py`). Formats: [sprite-grid-format.md](sprite-grid-format.md).
- Every command accepts `--verbose`. Default output is one line (`check`: one summary line plus one line
  per WARN/FAIL; `build`: at most 5 lines; `context`: at most 15 lines). Files written are identical in
  both modes.
- Exit codes: `0` success, `1` a quality check failed (`check`, `build`) or a game/character is missing
  (`context`, `game-style`), `2` an error (bad input, missing file, invalid option).
- Values that start with `-` must be attached with `=`: `--to=-1,0`, `--dx=-1`, `--offset=-3,0`.
- Default folders are relative to the current directory: `output/<project>/` for single-sprite commands
  (env `SPRITEWRIGHT_OUTPUT`), `outputs/` for games (`--root` or env `SPRITEWRIGHT_OUTPUTS`),
  `projects/` for loose sprite projects (env `SPRITEWRIGHT_PROJECTS`). Palettes are looked up as
  described in [palettes/README.md](../palettes/README.md).
"""


def _subparsers(parser):
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {a.dest: a.help for a in sub._choices_actions}
    return sub.choices, helps


def _value(a):
    if a.choices:
        return "{" + ",".join(map(str, a.choices)) + "}"
    if a.metavar:
        return a.metavar
    return a.dest.upper().rstrip("_")


def _takes_value(a):
    return a.nargs != 0 and not isinstance(a, (argparse._StoreTrueAction, argparse._StoreFalseAction,
                                                  argparse._StoreConstAction, argparse._CountAction))


def _positional(a):
    name = a.metavar or a.dest
    if a.nargs == "?":
        return f"[{name}]"
    if a.nargs == "+":
        return f"{name} [{name} ...]"
    if a.nargs == "*":
        return f"[{name} ...]"
    if a.nargs == argparse.REMAINDER:
        return f"[{name} ...]"
    return name


def _usage(name, p):
    parts = [f"spritewright {name}"]
    for a in p._actions:
        if isinstance(a, argparse._HelpAction) or a.option_strings:
            continue
        parts.append(_positional(a))
    for a in p._actions:
        if isinstance(a, argparse._HelpAction) or not a.option_strings:
            continue
        flag = a.option_strings[0]
        s = f"{flag} {_value(a)}" if _takes_value(a) else flag
        parts.append(s if a.required else f"[{s}]")
    return " ".join(parts)


def _default(a):
    d = a.default
    if d is None or d is False or d == argparse.SUPPRESS or not _takes_value(a):
        return ""
    if isinstance(d, tuple):
        return "x".join(map(str, d))
    if isinstance(d, float) and d.is_integer():
        return str(int(d))
    return str(d)


def _cell(text):
    """Help text -> Markdown text: pipes escaped, <Game> etc. not swallowed as HTML tags."""
    return (text or "").replace("|", "\\|").replace("\n", " ").replace("<", "&lt;").replace(">", "&gt;")


def _command_md(name, p, help_):
    desc = _cell(p.description or help_)
    out = [f"### `{name}`", "", desc[:1].upper() + desc[1:] + ".", "", "```text", _usage(name, p), "```", ""]
    rows = []
    actions = [a for a in p._actions if not isinstance(a, argparse._HelpAction)]
    for a in [a for a in actions if not a.option_strings] + [a for a in actions if a.option_strings]:
        if a.option_strings:
            flags = ", ".join(f"`{f}`" for f in a.option_strings)
            if _takes_value(a):
                flags += f" `{_value(a)}`"
        else:
            flags = f"`{_positional(a)}`"
        info = _cell(a.help)
        extra = []
        if a.required and a.option_strings:
            extra.append("required")
        d = _default(a)
        if d and "default" not in info:
            extra.append(f"default `{_cell(d)}`")
        if extra:
            info = (info + " " if info else "") + "(" + ", ".join(extra) + ")"
        rows.append(f"| {flags} | {info} |")
    out += ["| Argument | Description |", "|---|---|", *rows, ""]
    return out


def generate():
    parser = build_parser()
    choices, helps = _subparsers(parser)
    listed = [c for _, cmds in GROUPS for c in cmds]
    groups = [(t, [c for c in cmds if c in choices]) for t, cmds in GROUPS]
    other = [c for c in choices if c not in listed]
    if other:
        groups.append(("Other", other))
    lines = [HEADER.format(version=__version__).rstrip("\n"), "", "## Overview", ""]
    for title, cmds in groups:
        lines.append(f"**{title}**")
        lines.append("")
        for c in cmds:
            lines.append(f"- [`{c}`](#{c}) - {_cell(helps.get(c))}")
        lines.append("")
    for title, cmds in groups:
        lines += [f"## {title}", ""]
        for c in cmds:
            lines += _command_md(c, choices[c], helps.get(c))
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate docs/commands.md from the CLI parser")
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/commands.md is out of date")
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print("docs/commands.md is out of date: run python tools/gen_command_docs.py")
            return 1
        print("docs/commands.md is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
